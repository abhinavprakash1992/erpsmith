"""Site profile: short descriptive notes about this site (companies, currencies, warehouses, naming series, apps, workflows,
customization footprint), kept in MCP Memory so `search_memory` answers "which apps are installed here".

`build` regenerates them (`profile_notes` + `sync_profile`). A note is rewritten only when its text changed, so an unchanged
site embeds nothing. The notes are generated: an edit made to one is replaced on the next build.
"""

import frappe
from frappe.utils import nowdate

from erpsmith import memory

HEADER = "Generated by ERPSmith from this site's records; regenerated when they change. Edits made here are replaced on the next build."
COMPANIES_SHOWN = 20
WAREHOUSES_SHOWN = 30
DOCTYPES_SHOWN = 10
SERIES_SHOWN = 40
STANDARD_APPS = frozenset({"frappe", "erpnext", "hrms", "payments", "erpsmith"})
TITLES = {
	"companies": "Site profile: companies",
	"currencies": "Site profile: currencies",
	"warehouses": "Site profile: warehouses",
	"naming-series": "Site profile: naming series",
	"apps": "Site profile: apps and modules",
	"workflows": "Site profile: workflows",
	"footprint": "Site profile: custom apps and customization footprint",
}


def _note(*lines):
	return "\n".join([HEADER, *(line for line in lines if line)])


def _more(shown, total, noun):
	return f"and {total - shown} more {noun}." if total > shown else None


def format_companies(rows, fiscal_year):
	lines = []
	for r in rows[:COMPANIES_SHOWN]:
		parent = f", a subsidiary of {r['parent_company']}" if r.get("parent_company") else ""
		lines.append(f"- {r['name']} ({r.get('abbr') or '-'}), country {r.get('country') or '-'}, currency {r.get('default_currency') or '-'}{parent}")
	return _note(f"This site has {len(rows)} compan{'y' if len(rows) == 1 else 'ies'}.",
		fiscal_year and f"Current fiscal year: {fiscal_year}.", *lines, _more(COMPANIES_SHOWN, len(rows), "companies"))


def format_currencies(default, enabled, price_list_currencies):
	return _note(default and f"Default currency (Global Defaults): {default}.",
		f"Enabled currencies: {', '.join(enabled) or 'none'}.",
		price_list_currencies and f"Currencies used by Price Lists: {', '.join(price_list_currencies)}.")


def format_warehouses(rows, default, valuation):
	lines = [f"- {r['name']}: {r['children']} child warehouse{'' if r['children'] == 1 else 's'}" for r in rows[:WAREHOUSES_SHOWN]]
	return _note(f"This site has {len(rows)} group warehouse{'' if len(rows) == 1 else 's'}.",
		default and f"Default warehouse: {default}.", valuation and f"Valuation method: {valuation}.",
		*lines, _more(WAREHOUSES_SHOWN, len(rows), "group warehouses"))


def format_naming_series(series_by_doctype):
	"""One line per DocType, in the order given (the caller puts the DocTypes with most records first)."""
	if not series_by_doctype:
		return _note("No DocType with records on this site offers naming series.")
	items = list(series_by_doctype.items())
	return _note("Naming series by DocType, those with most records first:",
		*(f"- {dt}: {', '.join(series)}" for dt, series in items[:SERIES_SHOWN]), _more(SERIES_SHOWN, len(items), "DocTypes"))


def format_apps(apps, modules_with_rows):
	listed = ", ".join(f"{a['name']}{' ' + a['version'] if a.get('version') else ''}" for a in apps)
	used = [f"- {app}: {', '.join(modules)}" for app, modules in sorted(modules_with_rows.items()) if modules]
	return _note(f"Apps installed on this site: {listed}.", used and "Modules whose DocTypes hold records:", *used)


def format_workflows(rows):
	if not rows:
		return _note("This site has no workflows.")
	lines = [f"- {r['name']} on {r['document_type']} ({'active' if r.get('is_active') else 'inactive'}): states {', '.join(r.get('states') or []) or 'none'}"
		for r in rows]
	return _note(f"This site has {len(rows)} workflow{'' if len(rows) == 1 else 's'}.", *lines)


def format_footprint(custom_apps, counts, top_doctypes):
	return _note(f"Apps outside the standard set: {', '.join(custom_apps) if custom_apps else 'none'}.",
		"Customization records: " + ", ".join(f"{n} {label}" for label, n in counts.items()) + ".",
		top_doctypes and "Most customised DocTypes (custom fields plus property setters):",
		*(f"- {dt}: {n}" for dt, n in top_doctypes[:DOCTYPES_SHOWN]))


# --- gathering ---------------------------------------------------------------------------------------------------

def _have(*doctypes):
	"""True when every DocType exists on this site. The DocType record, not its table: a Single DocType has no table."""
	return all(frappe.db.exists("DocType", dt) for dt in doctypes)


def _companies():
	rows = frappe.get_all("Company", fields=["name", "abbr", "country", "default_currency", "parent_company"], order_by="name asc")
	year = frappe.get_all("Fiscal Year", filters={"year_start_date": ["<=", nowdate()], "year_end_date": [">=", nowdate()]},
		pluck="name", limit=1) if _have("Fiscal Year") else []
	return format_companies(rows, year[0] if year else None)


def _currencies():
	enabled = frappe.get_all("Currency", filters={"enabled": 1}, pluck="name", order_by="name asc")
	default = frappe.db.get_single_value("Global Defaults", "default_currency") if _have("Global Defaults") else None
	prices = frappe.get_all("Price List", filters={"currency": ["is", "set"]}, pluck="currency", distinct=True, order_by="currency asc") if _have("Price List") else []
	return format_currencies(default, enabled, prices)


def _warehouses():
	groups = frappe.get_all("Warehouse", filters={"is_group": 1}, pluck="name", order_by="name asc")
	children = {}
	for parent in frappe.get_all("Warehouse", filters={"parent_warehouse": ["in", groups]}, pluck="parent_warehouse") if groups else []:
		children[parent] = children.get(parent, 0) + 1
	default = valuation = None
	if _have("Stock Settings"):
		default = frappe.db.get_single_value("Stock Settings", "default_warehouse")
		valuation = frappe.db.get_single_value("Stock Settings", "valuation_method")
	return format_warehouses([{"name": g, "children": children.get(g, 0)} for g in groups], default, valuation)


def _row_counts():
	"""{DocType: estimated rows} for tables that hold rows, from one information_schema query (InnoDB estimates, enough for
	"does it hold records" and "which holds most"); None where that is not available (MariaDB only)."""
	if frappe.db.db_type != "mariadb":
		return None
	rows = frappe.db.sql("select table_name, table_rows from information_schema.tables where table_schema = database() "
		"and table_name like 'tab%%' and table_rows > 0")
	return {name[3:]: int(n) for name, n in rows}


def _naming_series(row_counts):
	options = {}
	for source, doctype_field in (("DocField", "parent"), ("Custom Field", "dt")):
		for r in frappe.get_all(source, filters={"fieldname": "naming_series"}, fields=[doctype_field, "options"]):
			options[r[doctype_field]] = r.options
	for r in frappe.get_all("Property Setter", filters={"field_name": "naming_series", "property": "options"}, fields=["doc_type", "value"]):
		options[r.doc_type] = r.value
	series = {dt: [s.strip() for s in (text or "").split("\n") if s.strip()] for dt, text in options.items()}
	series = {dt: s for dt, s in series.items() if s and (row_counts is None or dt in row_counts)}
	order = sorted(series, key=lambda dt: (-(row_counts or {}).get(dt, 0), dt))
	return format_naming_series({dt: series[dt] for dt in order})


def _modules_with_rows(row_counts):
	"""{app: [module]} for modules owning a DocType whose table holds rows."""
	app_of = {m.name: m.app_name for m in frappe.get_all("Module Def", fields=["name", "app_name"])}
	modules = {}
	for dt in frappe.get_all("DocType", fields=["name", "module"]):
		if dt.name in (row_counts or {}) and app_of.get(dt.module):
			modules.setdefault(app_of[dt.module], set()).add(dt.module)
	return {app: sorted(mods) for app, mods in modules.items()}


def _apps(row_counts):
	apps = []
	for name in frappe.get_installed_apps():
		try:
			version = frappe.get_attr(f"{name}.__version__")
		except Exception:
			version = None
		apps.append({"name": name, "version": version})
	return format_apps(apps, _modules_with_rows(row_counts))


def _workflows():
	rows = frappe.get_all("Workflow", fields=["name", "document_type", "is_active"], order_by="name asc")
	states = {}
	for r in frappe.get_all("Workflow Document State", fields=["parent", "state"], order_by="parent asc, idx asc"):
		states.setdefault(r.parent, []).append(r.state)
	return format_workflows([{**r, "states": states.get(r.name, [])} for r in rows])


def _footprint():
	"""Workflows have their own note and are left out of the counts, so adding one changes one note."""
	counts = {label: frappe.db.count(dt) for label, dt in (("custom fields", "Custom Field"), ("property setters", "Property Setter"),
		("server scripts", "Server Script"), ("client scripts", "Client Script"), ("notifications", "Notification"),
		("custom print formats", "Print Format")) if _have(dt)}
	per_doctype = {}
	for dt in frappe.get_all("Custom Field", pluck="dt") + frappe.get_all("Property Setter", pluck="doc_type"):
		per_doctype[dt] = per_doctype.get(dt, 0) + 1
	top = sorted(per_doctype.items(), key=lambda kv: (-kv[1], kv[0]))
	return format_footprint([a for a in frappe.get_installed_apps() if a not in STANDARD_APPS], counts, top)


def profile_notes():
	"""[{key, title, content}] for each note whose source DocTypes exist on this site. A note that fails is logged and left out."""
	erpnext = _have("Company")
	rows = _row_counts()
	wanted = [("companies", erpnext, _companies), ("currencies", True, _currencies), ("warehouses", erpnext and _have("Warehouse"), _warehouses),
		("naming-series", True, lambda: _naming_series(rows)), ("apps", True, lambda: _apps(rows)), ("workflows", True, _workflows),
		("footprint", True, _footprint)]
	notes = []
	for key, present, make in wanted:
		if not present:
			continue
		try:
			notes.append({"key": key, "title": TITLES[key], "content": make()})
		except Exception:
			frappe.log_error(title=f"ERPSmith: site profile note {key} failed")
	return notes


def sync_profile(notes):
	"""Make MCP Memory hold `notes` as `profile__<key>` rows (topic context, seed_key `profile-<key>`). A row is saved, and so
	embedded, only when its title or content changed; a deleted or edited note comes back as generated."""
	counts = {"added": 0, "updated": 0, "unchanged": 0}
	for note in notes:
		name, content = f"profile__{note['key']}", note["content"][:memory.MAX_CONTENT_CHARS].strip()
		if not frappe.db.exists(memory.DOCTYPE, name):
			frappe.get_doc({"doctype": memory.DOCTYPE, "name": name, "seed_key": f"profile-{note['key']}", "topic": "context",
				"title": note["title"], "content": content}).insert(ignore_permissions=True)
			counts["added"] += 1
			continue
		doc = frappe.get_doc(memory.DOCTYPE, name)
		if (doc.title, doc.content) == (note["title"], content):
			counts["unchanged"] += 1
			continue
		doc.title, doc.content = note["title"], content
		doc.save(ignore_permissions=True)
		counts["updated"] += 1
	return counts
